CREATE TABLE IF NOT EXISTS item_questions (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 item_id INT UNSIGNED NOT NULL,
 user_id INT UNSIGNED NOT NULL,
 content VARCHAR(500) NOT NULL,
 reply VARCHAR(500) DEFAULT NULL,
 replied_at DATETIME DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_questions_item (item_id,created_at),
 FOREIGN KEY (item_id) REFERENCES items(id) ON DELETE CASCADE,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_reviews (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 order_id INT UNSIGNED NOT NULL,
 rating TINYINT UNSIGNED NOT NULL,
 content VARCHAR(500) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_review_order (order_id),
 FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
 CONSTRAINT chk_review_rating CHECK (rating BETWEEN 1 AND 5)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
ALTER TABLE orders
 ADD KEY idx_orders_item (item_id),
 DROP INDEX uk_orders_item,
 ADD COLUMN active_item_id INT UNSIGNED GENERATED ALWAYS AS (CASE WHEN status <> 'cancelled' THEN item_id ELSE NULL END) VIRTUAL,
 ADD UNIQUE KEY uk_orders_active_item (active_item_id);
